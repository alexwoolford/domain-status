    /// Kills: `fill_city` / `fill_asn` panicking on a poisoned `RwLock` instead of
    /// returning `false` so `lookup_ip` is `None`.
    #[test]
    fn test_poisoned_locks_soft_fail() {
        let city = empty_cache();
        let asn = empty_cache();
        poison_cache(&city);
        poison_cache(&asn);
        let service = GeoIpService::from_caches(city, asn);
        assert!(!service.is_enabled());
        assert!(service.get_metadata().is_none());
        assert!(service.lookup_ip(TEST_IP).is_none());
    }

    /// Kills: `fill_city` treating poison as fatal so a working ASN cache is ignored.
    #[test]
    fn test_poisoned_city_still_returns_asn() {
        let city = empty_cache();
        poison_cache(&city);
        let service =
            GeoIpService::from_caches(city, wrap_reader(Some(reader_from_bytes(ASN_ONLY_MMDB))));
        let got = service
            .lookup_ip(TEST_IP)
            .expect("ASN hit must survive City lock poison");
        assert_eq!(got.asn, Some(64_496));
        assert_eq!(got.asn_org.as_deref(), Some("Example ASN"));
        assert!(got.country_code.is_none());
        assert!(got.city.is_none());
        assert!(!service.is_enabled());
        assert!(service.get_metadata().is_none());
    }

    /// Kills: treating a country-only City record as a miss (`fill_city` → `false`)
    /// or requiring city/subdivision names.
